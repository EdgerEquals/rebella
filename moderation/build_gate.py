#!/usr/bin/env python3
"""Write the passcode hash for the Rebella moderation gate into js/config.js.

Reads the passcode from REBELLA_SITE_PASSCODE (the same passcode as the Rebella site gate).
The plaintext passcode is never written to disk or printed; only a random
salt and a PBKDF2-HMAC-SHA256 hash are stored (the browser checks with Web Crypto).

Usage:
  REBELLA_SITE_PASSCODE='...' python3 build_gate.py      # set the hash
  python3 build_gate.py --unset                          # reset to placeholder
"""
import hashlib, os, secrets, sys, pathlib

ITERATIONS = 250_000
OUT = pathlib.Path(__file__).resolve().parent / "js" / "config.js"

PLACEHOLDER = """// Rebella moderation gate config
// PASSCODE NOT SET YET. Run:  REBELLA_SITE_PASSCODE='...' python3 build_gate.py
// Until then the gate will refuse every passcode.
window.REBELLA_GATE = { unset: true, algo: "PBKDF2-SHA256", iterations: %d, salt: "", hash: "" };
""" % ITERATIONS

def main():
    if "--unset" in sys.argv:
        OUT.write_text(PLACEHOLDER)
        print(f"config.js reset to UNSET placeholder ({OUT})")
        return 0
    code = os.environ.get("REBELLA_SITE_PASSCODE", "")
    if not code:
        OUT.write_text(PLACEHOLDER)
        print("REBELLA_SITE_PASSCODE is not set: wrote UNSET placeholder config.js")
        return 2
    salt = secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", code.encode("utf-8"), bytes.fromhex(salt), ITERATIONS).hex()
    OUT.write_text(
        "// Rebella moderation gate config (generated by build_gate.py; contains no plaintext)\n"
        f'window.REBELLA_GATE = {{ unset: false, algo: "PBKDF2-SHA256", iterations: {ITERATIONS}, '
        f'salt: "{salt}", hash: "{digest}" }};\n'
    )
    print("config.js written with salted hash (passcode not shown)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
