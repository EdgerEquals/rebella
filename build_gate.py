#!/usr/bin/env python3
"""Write the site-wide passcode hash for Rebella into js/config.js.

Reads REBELLA_SITE_PASSCODE from the environment. The plaintext is never written or printed;
only a random salt + PBKDF2-HMAC-SHA256 hash are stored (checked in the browser with Web Crypto).

  REBELLA_SITE_PASSCODE='...' python3 build_gate.py   # set the hash
  python3 build_gate.py --unset                       # reset to placeholder (gate refuses everything)
"""
import hashlib, os, secrets, sys, pathlib

ITERATIONS = 250_000
OUT = pathlib.Path(__file__).resolve().parent / "js" / "config.js"
PLACEHOLDER = f"""// Rebella site gate config
// PASSCODE NOT SET YET. Run:  REBELLA_SITE_PASSCODE='...' python3 build_gate.py
// Until then the gate refuses every passcode (nobody can get in). Do not publish in this state.
window.REBELLA_GATE = {{ unset: true, algo: "PBKDF2-SHA256", iterations: {ITERATIONS}, salt: "", hash: "" }};
"""

def main():
    code = "" if "--unset" in sys.argv else os.environ.get("REBELLA_SITE_PASSCODE", "")
    if not code:
        OUT.write_text(PLACEHOLDER)
        print("Wrote UNSET placeholder js/config.js" + ("" if "--unset" in sys.argv else " (REBELLA_SITE_PASSCODE not set)"))
        return 0 if "--unset" in sys.argv else 2
    salt = secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", code.encode("utf-8"), bytes.fromhex(salt), ITERATIONS).hex()
    OUT.write_text("// Rebella site gate config (generated by build_gate.py; contains no plaintext)\n"
                   f'window.REBELLA_GATE = {{ unset: false, algo: "PBKDF2-SHA256", iterations: {ITERATIONS}, salt: "{salt}", hash: "{digest}" }};\n')
    print("js/config.js written with salted hash (passcode not shown)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
