#!/usr/bin/env python3
"""Extract a compact physics subset from Edger's stratified sphere model for the Rebella rhythm site.

Source: EdgerEquals/sphere-holster model_data_v0.json (solver_v0.py output, ~1.3 MB). Never ship the full file.
Usage: python3 build_physics_subset.py /path/to/sphere-holster [case_id]   -> ../data/sphere-subset.json
All values are copied, not invented. The sphere model itself is flagged ESTIMATED PHYSICS (v0 prototype, nothing measured).
"""
import json, sys, os, hashlib, subprocess, math

src_dir = sys.argv[1] if len(sys.argv) > 1 else '/workspace/ssm-fx2'
case_id = sys.argv[2] if len(sys.argv) > 2 else 'base5'
path = os.path.join(src_dir, 'model_data_v0.json')
raw = open(path, 'rb').read()
d = json.loads(raw)
c = next(x for x in d['cases'] if x['id'] == case_id)
s = c['state']; M = d['meta']['materials']
try:
    commit = subprocess.check_output(['git', '-C', src_dir, 'rev-parse', 'HEAD'], text=True).strip()
except Exception:
    commit = None

def r4(x):
    return float(f'{x:.4g}') if isinstance(x, (int, float)) and x is not None else x

R = c['R_outer_mm']
layers = []
for L in c['layers']:
    m = M.get(L['key'], {})
    layers.append(dict(key=L['key'], name=L['name'], a=r4(L['a_mm'] / R), b=r4(L['b_mm'] / R),
                       Q=m.get('Q'), n=m.get('n'), cL=m.get('cL'), rho=m.get('rho'),
                       pyro=m.get('p_pyro_C_per_m2K'), piezo=m.get('d_piezo_C_per_N')))
modes = [dict(f=m['f'], Q=m['Q_eff'], tau=m['tau_ac_s'], share={k: r4(v) for k, v in m['share'].items()})
         for m in s['acoustic']['modes'][:8]]
step = 8
out = dict(
    provenance=dict(repo='EdgerEquals/sphere-holster', file='model_data_v0.json', commit=commit,
                    sha256=hashlib.sha256(raw).hexdigest(), case=case_id, case_label=c['label'],
                    model_status=d['meta']['status'], model_date=d['meta']['date'],
                    note='Compact subset copied by rhythm/tools/build_physics_subset.py. ESTIMATED PHYSICS: v0 paper model, nothing measured.'),
    phi=d['meta']['phi'], R_outer_mm=R, layers=layers,
    acoustic_l0=modes, gas_cavity=s['acoustic']['gas_cavity_modes'],
    thresholds=dict(T_ref_K=s['thermal']['T_quartz_in'], T_curie_bto_K=393.0, T_c_gddy_K=260.0, T_quartz_alpha_beta_K=846.15,
                    src='BTO Curie ~393 K [est] and quartz alpha-beta 846.15 K [lit] from solver_v0.py; Gd-Dy ~260 K from material name/flags'),
    crossings=[dict(f=x['f'], r=r4(x['r_mm'] / R), what=x['b']) for x in s['crossings']],
    thermal_track=[[r4(a / R), r4(f)] for a, f in s['thermal_track']][::3],
    balmer=[dict(nm=434.0, w=0.47), dict(nm=486.1, w=1.0), dict(nm=656.3, w=2.86)],
    vectors=[dict(domain=v['domain'], r0=r4(v["r_start_mm"] / R), r1=r4(v["r_end_mm"] / R), what=v['what']) for v in s['vectors']],
    transit=dict(r=[r4(x) for x in c['r_disp'][::step]], t_opt=[r4(x) for x in s['t_opt'][::step]], t_ac=[r4(x) for x in s['t_ac'][::step]]),
    drive=dict(electric=s['electric'].get('note'), magnetic=s['magnetic'].get('note'), source=s['source']),
    flags=s['flags'])
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'sphere-subset.json')
open(dst, 'w').write(json.dumps(out, separators=(',', ':')))
print(dst, os.path.getsize(dst), 'bytes')

# Tier-0 constants (inlined as a tiny script so the first paint needs no fetch). Same provenance as the JSON.
consts = dict(src=f"{out['provenance']['repo']}@{(commit or '')[:7]} {case_id}", phi=out['phi'],
              l0=[[m['f'], m['Q'], m['tau']] for m in modes[:5]], gas0=out['gas_cavity'][0],
              bandQ=[L['Q'] for L in layers[1:6]], bandLayer=[L['key'] for L in layers[1:6]],
              T=out['thresholds'], balmer=[[b['nm'], b['w']] for b in out['balmer']])
cdst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'js', 'site-consts.js')
open(cdst, 'w').write('/* generated by tools/build_physics_subset.py from ' + consts['src'] + ' (ESTIMATED PHYSICS) */\nwindow.RB_CONST=' + json.dumps(consts, separators=(',', ':')) + ';\n')
print(cdst, os.path.getsize(cdst), 'bytes')
