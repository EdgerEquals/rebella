# Bonnie's radio (YouTube) for Rebella: build step. Called from ONE place in _generator.py.
# Reads music/youtube/channels.json, keeps ONLY entries that Dad approved and that passed an age check, and writes
# music/youtube/stations.js (window.BONNIE_STATIONS) for the page. Placeholders and unapproved entries never ship.
import os, json, re, html as _h
HERE = os.path.dirname(os.path.abspath(__file__))
ID_RE = re.compile(r'^[A-Za-z0-9_-]{12,64}$')

def _list_id(e):
    y = str(e.get('youtubeId') or '')
    if y.startswith('REPLACE_') or not ID_RE.match(y): return None
    if e.get('type') == 'channel':
        return ('UU' + y[2:]) if y.startswith('UC') else None   # uploads playlist of the channel, no API key needed
    if e.get('type') == 'playlist': return y
    return None

def _age_ok(e):
    a = e.get('ageCheck') or {}
    return (a.get('madeForKids') is True or a.get('ageSuitable') is True) and bool(a.get('checkedOn'))

def build():
    reg = json.load(open(os.path.join(HERE, 'channels.json'), encoding='utf-8'))
    TAGS = ('flavour', 'bpm', 'key_root', 'mode')               # typical tags the Music Playground band follows
    genres = [dict({'key': g['key'], 'label': g['label']}, **{t: g[t] for t in TAGS if t in g}) for g in reg['genres']]
    keys = {g['key'] for g in genres}
    pools = {g['key']: [] for g in genres}; main = []; reading = []; skipped = []
    for e in reg['entries']:
        lid = _list_id(e)
        if not (lid and e.get('approvedByDad') is True and _age_ok(e)):
            skipped.append(e.get('id')); continue
        item = {'id': e['id'], 'name': e.get('name', ''), 'list': lid}
        if 'main' in e.get('genres', []): main.append(item)
        if 'reading' in e.get('genres', []): reading.append(item)   # Playground 'Reading music' button
        for g in e.get('genres', []):
            if g in keys: pools[g].append(item)
        if e.get('type') == 'channel' and 'indie-local' in keys and item not in pools['indie-local']:
            pools['indie-local'].append(item)                     # every approved indie channel also joins Indie / Local
    data = {'genres': genres, 'main': main, 'reading': reading, 'pools': pools}
    js = ('/* generated by music/youtube/_yt_music.py from channels.json: approved + age-checked entries only. Do not edit. */\n'
          'window.BONNIE_STATIONS = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
    open(os.path.join(HERE, 'stations.js'), 'w', encoding='utf-8').write(js)
    return data, skipped

def section():
    return ('<section class="container br-home" aria-labelledby="br-title" data-bonnie-radio>'
            '<h2 id="br-title" class="br-title">Bonnie\'s radio</h2>'
            '<noscript><p class="br-note">Bonnie\'s radio needs JavaScript. It plays from YouTube.</p></noscript>'
            '</section>')

HEAD = ('\n<link rel="stylesheet" href="music/youtube/bonnie-radio.css?v=1">'
        '\n<script src="music/youtube/stations.js?v=1" defer></script>'
        '\n<script src="music/youtube/bonnie-radio.js?v=5" defer></script>')
